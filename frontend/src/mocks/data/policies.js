const withDefaults = (policy, index) => ({
  applyPeriodType: APPLY_PERIOD_TYPE.PERIOD,
  applyStartDate: dateFromToday(-30),
  viewCount: 1200 - index * 37,
  createdAt: dateFromToday(-index - 1),
  ...policy,
});

export const POLICIES = [...BASE_POLICIES, ...variantPolicies].map(withDefaults);

export const findPolicyById = (policyId) =>
  POLICIES.find((policy) => policy.id === Number(policyId));
